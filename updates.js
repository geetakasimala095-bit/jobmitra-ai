/* =========================================================
   SORT — NEWEST UPDATE FIRST
   ========================================================= */

function getLatestUpdates() {

  return JOBMITRA_UPDATES
    .filter(item => item.active === true)
    .sort(function(a, b) {

      return new Date(b.notificationDate) -
             new Date(a.notificationDate);

    });
}


